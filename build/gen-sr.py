#!/usr/bin/env python3
"""T1 · 生成 SR.g.cs —— 替代上游 Arcade 的 GenerateCommonSRSource 目标。

背景
----
上游 WPF 用 Arcade SDK 的 `GenerateCommonSRSource` 目标，在编译期把
`PresentationBuildTasks/Resources/Strings.resx` 翻译成 `SR.common.cs`：
    internal partial class SR {
        ResourceManager ResourceManager => ...;
        internal static string Foo => GetResourceString("Foo");
    }
手工编写的 SR.cs / Common/src/System/SR.cs 只是「另一半」partial class，
依赖生成文件补上 ResourceManager 与全部字符串属性。

本工程不引入 Arcade（见 PORT-CHANGES.md 改动4），因此在这里用同一个 resx
生成等价代码。输出落在 build/PresentationBuildTasks.Linux/，**不碰上游**。

用法：python3 build/gen-sr.py [--resx PATH] [--out PATH] [--basename NAME]
"""

import argparse
import sys
import xml.etree.ElementTree as ET

HEADER = """// <auto-generated>
//   由 build/gen-sr.py 自动生成，请勿手改。
//   来源：{src}（{count} 条）
//   作用：替代 Arcade 的 GenerateCommonSRSource 目标。改动详情见 PORT-CHANGES.md。
// </auto-generated>

namespace {ns}
{{
    internal partial class SR
    {{
        private static global::System.Resources.ResourceManager s_resourceManager;

        // 基线名必须与 csproj 里 EmbeddedResource 的 LogicalName 一致，
        // 否则运行时抛 MissingManifestResourceException。
        internal static global::System.Resources.ResourceManager ResourceManager =>
            s_resourceManager ??= new global::System.Resources.ResourceManager(
                "{basename}", typeof(SR).Assembly);

{body}
    }}
}}
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--resx", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--basename", default="PresentationBuildTasks.Resources.Strings")
    ap.add_argument("--ns", default="MS.Utility",
                    help="生成 SR 类所在的命名空间，必须与 Common/src/System/SR.cs 中"
                         "该项目 DefineConstants 命中的分支一致")
    args = ap.parse_args()

    root = ET.parse(args.resx).getroot()
    entries = [d for d in root.findall("data") if d.get("name")]
    if not entries:
        sys.exit("resx 中没有解析到任何 <data name=...> 条目")

    lines = []
    seen = set()
    for d in entries:
        name = d.get("name")
        # resx 的 name 可能带点号（如 "Foo.Bar"），C# 属性名不能带点，
        # 但 GetResourceString 的 key 必须保持原样，故只转属性名。
        prop = name.replace(".", "_").replace("-", "_")
        if prop in seen:
            continue
        seen.add(prop)
        # 把 resx 里的原文作为 defaultString 传入 GetResourceString(key, default)：
        # 即便资源基线名/嵌入路径与上游不一致，运行时也能拿到正确文本，
        # 不会因为 MissingManifestResourceException 导致整片功能不可用。
        val_el = d.find("value")
        val = (val_el.text or "") if val_el is not None else ""
        val = val.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\r", "")
        lines.append(
            '        internal static string {0} => GetResourceString("{1}", "{2}");'.format(
                prop, name.replace('"', '\\"'), val
            )
        )

    src = HEADER.format(count=len(seen), basename=args.basename, body="\n".join(lines),
                        ns=args.ns, src=args.resx)
    with open(args.out, "w", encoding="utf-8") as f:
        f.write(src)
    print("已生成 {} ：{} 条资源属性".format(args.out, len(seen)))


if __name__ == "__main__":
    main()
